        // Hàm tính tổng tiền của giỏ hàng
    private void tinhTongTien() {
        java.math.BigDecimal tong = java.math.BigDecimal.ZERO;
        for (int i = 0; i < tblGioHang.getRowCount(); i++) {
            tong = tong.add((java.math.BigDecimal) tblGioHang.getValueAt(i, 4));
        }
        lblTongTien.setText("Tổng tiền: " + String.format("%,.0f", tong) + " VNĐ");
    }

