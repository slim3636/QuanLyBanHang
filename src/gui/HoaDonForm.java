    private void btnThemVaoGioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemVaoGioActionPerformed
        // TODO add your handling code here:
         try {
            // 1. Lấy Mã SP từ ComboBox (Cắt chuỗi "1 - Nồi cơm" lấy số 1)
            String selectedSP = cboSanPham.getSelectedItem().toString();
            int maSP = Integer.parseInt(selectedSP.split(" - ")[0]);
            String tenSP = selectedSP.split(" - ")[1];
            
            // 2. Lấy số lượng nhập vào
            int soLuong = Integer.parseInt(txtSoLuong.getText().trim());
            if (soLuong <= 0) {
                JOptionPane.showMessageDialog(this, "Số lượng phải lớn hơn 0!");
                return;
            }
            
            // 3. Tìm giá của sản phẩm này
            java.math.BigDecimal donGia = java.math.BigDecimal.ZERO;
            java.util.List<Object[]> listSP = spDAO.getAll();
            for (Object[] sp : listSP) {
                if ((int)sp[0] == maSP) {
                    donGia = (java.math.BigDecimal) sp[2];
                    break;
                }
            }
            
            // 4. Tính thành tiền
            java.math.BigDecimal thanhTien = donGia.multiply(new java.math.BigDecimal(soLuong));
            
                        // 5. Kiểm tra xem sản phẩm đã có trong giỏ hàng chưa
            boolean daCoTrongGio = false;
            for (int i = 0; i < tblGioHang.getRowCount(); i++) {
                int maSPTrongGio = (int) tblGioHang.getValueAt(i, 0);
                if (maSPTrongGio == maSP) {
                    // Nếu có rồi thì cộng dồn số lượng
                    int soLuongCu = (int) tblGioHang.getValueAt(i, 2);
                    int soLuongMoi = soLuongCu + soLuong;
                    java.math.BigDecimal thanhTienMoi = donGia.multiply(new java.math.BigDecimal(soLuongMoi));
                    
                    // Cập nhật lại bảng
                    tblGioHang.setValueAt(soLuongMoi, i, 2);
                    tblGioHang.setValueAt(thanhTienMoi, i, 4);
                    
                    // Cập nhật lại list tạm (Xóa cái cũ, thêm cái mới)
                    gioHang.remove(i);
                    gioHang.add(i, new Object[]{ maSP, soLuongMoi, donGia });
                    
                    daCoTrongGio = true;
                    break;
                }
            }
            
            // Nếu chưa có trong giỏ thì mới thêm dòng mới
            if (!daCoTrongGio) {
                modelGioHang.addRow(new Object[]{ maSP, tenSP, soLuong, donGia, thanhTien });
                gioHang.add(new Object[]{ maSP, soLuong, donGia });
            }
            
            // 6. Cập nhật tổng tiền
            tinhTongTien();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sản phẩm và nhập số lượng hợp lệ!");
        }
    }//GEN-LAST:event_btnThemVaoGioActionPerformed

    private void btnLuuHoaDonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuHoaDonActionPerformed
        // TODO add your handling code here:
         if (gioHang.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Giỏ hàng đang trống, vui lòng thêm sản phẩm!");
            return;
        }
        
        try {
            // 1. Lấy Mã Khách Hàng từ ComboBox
            String selectedKH = cboKhachHang.getSelectedItem().toString();
            int maKH = Integer.parseInt(selectedKH.split(" - ")[0]);
            
            // 2. Lấy ngày lập (định dạng yyyy-mm-dd)
            java.sql.Date ngayLap = java.sql.Date.valueOf(txtNgayLap.getText());
            
            // 3. Gọi hàm lưu từ DAO
            if (hdDAO.insertHoaDon(maKH, ngayLap, gioHang)) {
                JOptionPane.showMessageDialog(this, "Lưu hóa đơn thành công!");
                
                // 4. Reset form sau khi lưu
                gioHang.clear();
                modelGioHang.setRowCount(0);
                lblTongTien.setText("Tổng tiền: 0 VNĐ");
                txtSoLuong.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Lưu hóa đơn thất bại! Vui lòng kiểm tra lại kết nối hoặc dữ liệu.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Vui lòng kiểm tra lại ngày lập (Định dạng: yyyy-mm-dd)!");
        }
    }//GEN-LAST:event_btnLuuHoaDonActionPerformed

