    public void loadData() {
        // Khởi tạo model cho bảng với 5 cột
        tableModel = new javax.swing.table.DefaultTableModel(
            new Object [][] {},
            new String [] {"Mã SP", "Tên SP", "Đơn Giá", "Số Lượng Tồn", "Đơn Vị Tính"}
        );
        // Gán model cho bảng
        tblSanPham.setModel(tableModel);
        
        // Lấy dữ liệu từ DAO
        java.util.List<Object[]> list = spDAO.getAll();
        
        // Đổ dữ liệu vào bảng
        for (Object[] row : list) {
            tableModel.addRow(row);
        }
    }
        // Hàm xử lý sự kiện click chuột vào bảng
        private void initTableEvent() {
        tblSanPham.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int row = tblSanPham.getSelectedRow();
                if (row >= 0) {
                    txtTenSP.setText(tblSanPham.getValueAt(row, 1).toString());
                    txtDonGia.setText(tblSanPham.getValueAt(row, 2).toString());
                    txtSoLuongTon.setText(tblSanPham.getValueAt(row, 3).toString());
                    txtDonViTinh.setText(tblSanPham.getValueAt(row, 4) != null ? tblSanPham.getValueAt(row, 4).toString() : "");
                }
            }
        });
    
    }
