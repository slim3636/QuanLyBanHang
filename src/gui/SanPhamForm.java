    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:
        try {
            String tenSP = txtTenSP.getText().trim();
            java.math.BigDecimal donGia = new java.math.BigDecimal(txtDonGia.getText().trim());
            int soLuongTon = Integer.parseInt(txtSoLuongTon.getText().trim());
            String donViTinh = txtDonViTinh.getText().trim();
            
            if (tenSP.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập tên sản phẩm!");
                return;
            }
            
            if (spDAO.insert(tenSP, donGia, soLuongTon, donViTinh)) {
                JOptionPane.showMessageDialog(this, "Thêm thành công!");
                loadData();
                txtTenSP.setText(""); txtDonGia.setText(""); txtSoLuongTon.setText(""); txtDonViTinh.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Thêm thất bại!");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đúng định dạng số cho Đơn giá và Số lượng!");
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
         int row = tblSanPham.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sản phẩm cần sửa!");
            return;
        }
        try {
            int maSP = Integer.parseInt(tblSanPham.getValueAt(row, 0).toString());
            String tenSP = txtTenSP.getText().trim();
            java.math.BigDecimal donGia = new java.math.BigDecimal(txtDonGia.getText().trim());
            int soLuongTon = Integer.parseInt(txtSoLuongTon.getText().trim());
            String donViTinh = txtDonViTinh.getText().trim();
            
            if (spDAO.update(maSP, tenSP, donGia, soLuongTon, donViTinh)) {
                JOptionPane.showMessageDialog(this, "Sửa thành công!");
                loadData();
            } else {
                JOptionPane.showMessageDialog(this, "Sửa thất bại!");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đúng định dạng số!");
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
         int row = tblSanPham.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sản phẩm cần xóa!");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa sản phẩm này?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            int maSP = Integer.parseInt(tblSanPham.getValueAt(row, 0).toString());
            if (spDAO.delete(maSP)) {
                JOptionPane.showMessageDialog(this, "Xóa thành công!");
                loadData();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại (Có thể do sản phẩm đã có trong hóa đơn)!");
            }
        }
    }//GEN-LAST:event_btnXoaActionPerformed

