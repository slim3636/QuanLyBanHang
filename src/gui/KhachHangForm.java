    private void tblKhachHangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblKhachHangMouseClicked
      int row = tblKhachHang.getSelectedRow();
        if (row >= 0) {
            txtHoTen.setText(tblKhachHang.getValueAt(row, 1).toString());
            txtSDT.setText(tblKhachHang.getValueAt(row, 2) != null ? tblKhachHang.getValueAt(row, 2).toString() : "");
            txtDiaChi.setText(tblKhachHang.getValueAt(row, 3) != null ? tblKhachHang.getValueAt(row, 3).toString() : "");
        }
    }//GEN-LAST:event_tblKhachHangMouseClicked

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        int row = tblKhachHang.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn khách hàng cần sửa!");
            return;
        }
        
        int maKH = Integer.parseInt(tblKhachHang.getValueAt(row, 0).toString());
        String hoTen = txtHoTen.getText().trim();
        String sdt = txtSDT.getText().trim();
        String diaChi = txtDiaChi.getText().trim();
        
        if (khDAO.update(maKH, hoTen, sdt, diaChi)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Sửa thành công!");
            loadData();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Sửa thất bại!");
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:
        String hoTen = txtHoTen.getText().trim();
        String sdt = txtSDT.getText().trim();
        String diaChi = txtDiaChi.getText().trim();
        
        if (hoTen.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập họ tên!");
            return;
        }
        
        if (khDAO.insert(hoTen, sdt, diaChi)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Thêm thành công!");
            loadData();
            txtHoTen.setText(""); txtSDT.setText(""); txtDiaChi.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Thêm thất bại!");
        }
    }//GEN-LAST:event_btnThemActionPerformed

