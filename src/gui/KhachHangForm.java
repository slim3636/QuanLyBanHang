    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
         int row = tblKhachHang.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn khách hàng cần xóa!");
            return;
        }
        
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa?", "Xác nhận", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            int maKH = Integer.parseInt(tblKhachHang.getValueAt(row, 0).toString());
            if (khDAO.delete(maKH)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Xóa thành công!");
                loadData();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Xóa thất bại (Có thể do ràng buộc)!");
            }
        }
    }//GEN-LAST:event_btnXoaActionPerformed

